  function detect() {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved === 'zh') {
        try { localStorage.setItem(STORAGE_KEY, 'zh-Hans'); } catch {}
        return 'zh-Hans';
      }
      if (saved && dict[saved]) return saved;
    } catch {}
    const prefs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || ''];
    const language = (prefs[0] || '').replaceAll('_', '-');
    if (/^zh(?:-|$)/i.test(language)) {
      return /^zh-(?:Hant|TW|HK|MO)(?:-|$)/i.test(language) ? 'zh-Hant' : 'zh-Hans';
    }
    return 'en';
  }

  let lang = detect();
  const listeners = new Set();
  const locale = () => ({ 'zh-Hans': 'zh-CN', 'zh-Hant': 'zh-TW', en: 'en' })[lang];

  function t(key, vars) {
    const s = dict[lang][key] ?? dict['zh-Hans'][key] ?? key;
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m)) : s;
  }

